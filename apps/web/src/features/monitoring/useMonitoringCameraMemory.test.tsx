import { createRef, StrictMode } from "react";
import { act, cleanup, renderHook } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { useMonitoringCameraMemory } from "./useMonitoringCameraMemory";
import { monitoringCameraStore } from "./monitoring-camera-storage";
import type { FloorMapViewportHandle } from "../floor-map/FloorMapViewport";
const snapshot = { floorId: "f", revision: 1, width: 600, height: 400, objects: [], floorPlan: null };
const scope = { principal: "p", siteId: "s", floorId: "f" };
const camera = { centerXRatio: .7, centerYRatio: .3, zoom: 2 };
afterEach(() => { cleanup(); localStorage.clear(); monitoringCameraStore.clearMemory(); vi.useRealTimers(); vi.restoreAllMocks(); });
it("restores before saving, debounces writes and survives StrictMode replay", () => {
  vi.useFakeTimers();
  monitoringCameraStore.save(scope, JSON.stringify(["legacy:1", 600, 400]), camera);
  const handle = { getCamera: vi.fn(() => camera), restoreCamera: vi.fn(), centerOn: vi.fn(), fit: vi.fn() };
  const viewport = createRef<FloorMapViewportHandle>();
  Object.assign(viewport, { current: handle });
  const save = vi.spyOn(monitoringCameraStore, "save");
  const { result, unmount } = renderHook(() => useMonitoringCameraMemory(scope, snapshot, viewport), { wrapper: StrictMode });
  act(() => result.current.onCameraSettled({ ...camera, zoom: 1 }));
  act(() => vi.advanceTimersByTime(400));
  expect(save).not.toHaveBeenCalled();
  act(() => result.current.onCameraReady());
  expect(handle.restoreCamera).toHaveBeenCalledOnce();
  expect(handle.restoreCamera).toHaveBeenCalledWith(camera);
  act(() => { result.current.onCameraSettled(camera); result.current.onCameraSettled({ ...camera, zoom: 3 }); });
  act(() => vi.advanceTimersByTime(299));
  expect(save).not.toHaveBeenCalled();
  act(() => vi.advanceTimersByTime(1));
  expect(save).toHaveBeenCalledWith(scope, JSON.stringify(["legacy:1", 600, 400]), { ...camera, zoom: 3 });
  act(() => result.current.onCameraSettled(camera));
  unmount();
  expect(save).toHaveBeenCalledTimes(2);
});
it("rearms restoration after an effect teardown replay", () => {
  const handle = { getCamera: vi.fn(() => camera), restoreCamera: vi.fn(), centerOn: vi.fn(), fit: vi.fn() };
  const viewport = createRef<FloorMapViewportHandle>(); Object.assign(viewport, { current: handle });
  const { result } = renderHook(() => useMonitoringCameraMemory(scope, snapshot, viewport));
  act(() => result.current.onCameraReady());
  expect(handle.fit).toHaveBeenCalledTimes(1);
  act(() => result.current.release());
  act(() => result.current.onCameraReady());
  expect(handle.fit).toHaveBeenCalledTimes(2);
});
it("flushes the old scope and restores only after the new viewport is ready", () => {
  vi.useFakeTimers();
  const handle = { getCamera: vi.fn(() => camera), restoreCamera: vi.fn(), centerOn: vi.fn(), fit: vi.fn() };
  const viewport = createRef<FloorMapViewportHandle>();
  Object.assign(viewport, { current: handle });
  const { result, rerender } = renderHook(({ floorId }) => useMonitoringCameraMemory({ ...scope, floorId }, snapshot, viewport), { initialProps: { floorId: "f" } });
  act(() => { result.current.onCameraReady(); result.current.onCameraSettled(camera); });
  rerender({ floorId: "f2" });
  expect(monitoringCameraStore.load(scope, JSON.stringify(["legacy:1", 600, 400]))).toEqual(camera);
  expect(handle.fit).toHaveBeenCalledTimes(1);
  act(() => result.current.onCameraReady());
  expect(handle.fit).toHaveBeenCalledTimes(2);
});
